const LanguageContext = createContext<LanguageContextType>({
  locale: "en",
  setLocale: () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("spanel_locale") as Locale | null;
      if (saved && (saved === "en" || saved === "id")) {
        setLocaleState(saved);
      }
    } catch {
      // LocalStorage unavailable in SSR / sandbox
    }
  }, []);

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem("spanel_locale", newLocale);
    } catch {
      // ignore
    }
  };

  const t = (key: string): string => {
    const locDict = translations[locale];
    if (locDict && locDict[key]) return locDict[key];
    const enDict = translations.en;
    if (enDict && enDict[key]) return enDict[key];
    return key;
  };

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

